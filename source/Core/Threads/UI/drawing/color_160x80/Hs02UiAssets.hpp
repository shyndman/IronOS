inline const Font *selectFont(uint8_t pxSize) {
  switch (pxSize) {
  case 15:
    return &kFont15;
  case 17:
    return &kFont17;
  case 30:
    return &kFont30;
  case 19:
  default:
    return &kFont19;
  }
}

inline const Glyph *findGlyph(const Font *font, uint8_t code) {
  uint8_t lo = 0;
  uint8_t hi = font->glyphCount;
  while (lo < hi) {
    const uint8_t mid = static_cast<uint8_t>((lo + hi) / 2u);
    const uint8_t cur = font->glyphs[mid].code;
    if (cur == code) {
      return &font->glyphs[mid];
    }
    if (cur < code) {
      lo = static_cast<uint8_t>(mid + 1u);
    } else {
      hi = mid;
    }
  }
  return nullptr;
}

